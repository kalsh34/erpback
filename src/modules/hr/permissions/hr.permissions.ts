import { registerModule } from '../../../core/permissions/registry';
import { UserRole, PERMISSIONS } from '../../../types';

export function registerHRPermissions(): void {
  registerModule({
    module: 'hr',
    permissions: [
      PERMISSIONS.EMPLOYEE_CREATE,
      PERMISSIONS.EMPLOYEE_READ,
      PERMISSIONS.EMPLOYEE_UPDATE,
      PERMISSIONS.EMPLOYEE_DELETE,
      PERMISSIONS.SITE_CREATE,
      PERMISSIONS.SITE_READ,
      PERMISSIONS.SITE_UPDATE,
      PERMISSIONS.GUARD_REGISTER,
      PERMISSIONS.GUARD_ASSIGN_SITE,
      PERMISSIONS.GUARD_MODIFY_HOURS,
      PERMISSIONS.ATTENDANCE_READ,
      PERMISSIONS.ATTENDANCE_CLOCK,
      PERMISSIONS.ATTENDANCE_MANAGE,
      PERMISSIONS.STAFF_ATTENDANCE_MANAGE,
      PERMISSIONS.ORGANIZATION_READ,
      PERMISSIONS.ORGANIZATION_MANAGE,

    ],
    roleDefaults: {
      [UserRole.HR_ADMIN]: [
        PERMISSIONS.EMPLOYEE_CREATE,
        PERMISSIONS.EMPLOYEE_READ,
        PERMISSIONS.EMPLOYEE_UPDATE,
        PERMISSIONS.SITE_CREATE,
        PERMISSIONS.SITE_READ,
        PERMISSIONS.SITE_UPDATE,
        PERMISSIONS.GUARD_REGISTER,
        PERMISSIONS.GUARD_ASSIGN_SITE,
        PERMISSIONS.ATTENDANCE_READ,
        PERMISSIONS.ATTENDANCE_MANAGE,
        PERMISSIONS.STAFF_ATTENDANCE_MANAGE,
        PERMISSIONS.ORGANIZATION_READ,
        PERMISSIONS.ORGANIZATION_MANAGE,

      ],
      [UserRole.OPERATIONS]: [
        PERMISSIONS.EMPLOYEE_READ,
        PERMISSIONS.SITE_READ,
        PERMISSIONS.GUARD_ASSIGN_SITE,
        PERMISSIONS.GUARD_MODIFY_HOURS,
        PERMISSIONS.ATTENDANCE_READ,
      ],
      [UserRole.GUARD]: [
        PERMISSIONS.ATTENDANCE_CLOCK,
        PERMISSIONS.EMPLOYEE_READ,
        PERMISSIONS.SITE_READ,
      ],
    },
  });
}
